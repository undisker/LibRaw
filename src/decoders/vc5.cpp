static inline int vc5_clamp16(int v)
{
  return v < -32768 ? -32768 : (v > 32767 ? 32767 : v);
}

static inline int vc5_clamp_u14(int v)
{
  return v < 0 ? 0 : (v > 16383 ? 16383 : v);
}

/* ------------------------------------------------------------------------
   Bit reader: MSB first, bounded by the chunk it was created for.
   Reads past the end deliver zero bits and are counted in 'pad', so that
   the callers can detect an overrun without ever touching foreign memory.
   ------------------------------------------------------------------------ */
struct vc5_bits_t
{
  const uchar *p, *end;
  UINT64 buf;
  int n;     /* valid bits in buf (including padding bits) */
  INT64 pad; /* padding bits appended after the end of the data */

  vc5_bits_t(const uchar *data, size_t bytes)
      : p(data), end(data + bytes), buf(0), n(0), pad(0)
  {
  }
  /* after fill() at least 57 bits are available */
  inline void fill()
  {
    while (n <= 56)
    {
      if (p < end)
        buf |= UINT64(*p++) << (56 - n);
      else
        pad += 8;
      n += 8;
    }
  }
  inline unsigned peek(int count) const /* 1..32 */
  {
    return unsigned(buf >> (64 - count));
  }
  inline void skip(int count)
  {
    buf <<= count;
    n -= count;
  }
  inline bool overrun() const { return pad > INT64(n); }
};

/* ------------------------------------------------------------------------
   Variable length codes: direct lookup for short codewords, linear search
   (as the reference decoder does for all codewords) for the long, rare ones.
   ------------------------------------------------------------------------ */
struct vc5_lut_t
{
  uchar len; /* 0: codeword is longer than VC5_LUT_BITS */
  uchar value;
  ushort count;
};

struct vc5_vlc_t
{
  vc5_lut_t lut[1 << VC5_LUT_BITS];
  int first_long;
};

static void vc5_build_vlc(vc5_vlc_t &vlc)
{
  memset(vlc.lut, 0, sizeof(vlc.lut));
  vlc.first_long = VC5_CODEBOOK_LENGTH;
  for (int i = 0; i < VC5_CODEBOOK_LENGTH; i++)
  {
    const vc5_rlv_t &e = vc5_codebook17[i];
    if (e.size > VC5_LUT_BITS)
    {
      /* the codebook is sorted by codeword size */
      if (i < vlc.first_long)
        vlc.first_long = i;
      continue;
    }
    const unsigned shift = VC5_LUT_BITS - e.size;
    const unsigned base = e.bits << shift;
    for (unsigned k = 0; k < (1u << shift); k++)
    {
      vc5_lut_t &l = vlc.lut[base + k];
      l.len = e.size;
      l.value = uchar(e.value);
      l.count = e.count;
    }
  }
}

/* Needs at least VC5_MAX_CODE_BITS bits in the reader. Returns false if no
   codeword matches (cannot happen with codebook #17, which is complete). */
static inline bool vc5_get_rlv(vc5_bits_t &bits, const vc5_vlc_t &vlc,
                               unsigned &count, unsigned &value)
{
  const vc5_lut_t &l = vlc.lut[bits.peek(VC5_LUT_BITS)];
  if (l.len)
  {
    bits.skip(l.len);
    count = l.count;
    value = l.value;
    return true;
  }
  const unsigned w = bits.peek(VC5_MAX_CODE_BITS);
  for (int i = vlc.first_long; i < VC5_CODEBOOK_LENGTH; i++)
  {
    const vc5_rlv_t &e = vc5_codebook17[i];
    if ((w >> (VC5_MAX_CODE_BITS - e.size)) == e.bits)
    {
      bits.skip(e.size);
      count = e.count;
      value = e.value;
      return true;
    }
  }
  return false;
}

/* Decode one highpass band (run lengths of zeros and signed magnitudes),
   undo the cubic companding curve and the quantization.
   Returns non-zero if the data is damaged. */
static int vc5_decode_highpass(const uchar *data, size_t bytes, short *out,
                               size_t total, int quant, const vc5_vlc_t &vlc)
{
  /* dequantized value for every magnitude in the codebook, [1]: negative */
  short dq[2][VC5_MAX_MAGNITUDE + 1];
  for (int m = 0; m <= VC5_MAX_MAGNITUDE; m++)
  {
    /* f(x) = x + x^3 * 768 / 255^3; the division truncates like the
       conversion from double in the reference code */
    const INT64 mag = INT64(m) + (INT64(m) * m * m * 768) / 16581375;
    const INT64 v = INT64(quant) * mag;
    dq[0][m] = short(v < -32768 ? -32768 : (v > 32767 ? 32767 : v));
    dq[1][m] = short(-v < -32768 ? -32768 : (-v > 32767 ? 32767 : -v));
  }

  vc5_bits_t bits(data, bytes);
  size_t done = 0;
  unsigned count = 0, value = 0;
  while (done < total)
  {
    bits.fill();
    if (bits.pad && bits.overrun())
      return 1;
    if (!vc5_get_rlv(bits, vlc, count, value))
      return 1;
    if (!count) /* special codeword inside of the band */
      return 1;
    if (count > total - done)
      return 1;
    if (value)
    {
      const unsigned sign = bits.peek(1);
      bits.skip(1);
      const short v = dq[sign][value];
      for (unsigned k = 0; k < count; k++)
        out[done + k] = v;
    }
    else
      memset(out + done, 0, size_t(count) * sizeof(short));
    done += count;
  }
  /* The band is followed by the band end codeword. As in the reference
     decoder any special codeword or the magnitude 1 is accepted here. */
  bits.fill();
  if (!vc5_get_rlv(bits, vlc, count, value))
    return 1;
  if (!(count == 0 || value == 1))
    return 1;
  return bits.overrun() ? 1 : 0;
}

/* Decode the lowpass band: fixed size unsigned values, stored like the
   reference does in signed 16 bit (only the low 16 bits are kept). */
static int vc5_decode_lowpass(const uchar *data, size_t bytes, short *out,
                              size_t total, int precision)
{
  if (precision < 8 || precision > 32)
    return 1;
  if (INT64(total) * precision > INT64(bytes) * 8)
    return 1;
  vc5_bits_t bits(data, bytes);
  for (size_t i = 0; i < total; i++)
  {
    bits.fill();
    const unsigned v = bits.peek(precision) & 0xffffu;
    bits.skip(precision);
    out[i] = short(v >= 0x8000u ? int(v) - 0x10000 : int(v));
  }
  return bits.overrun() ? 1 : 0;
}

