void LibRaw::vc5_dng_load_raw()
{
  if (!dng_version || tiff_samples != 1)
    throw LIBRAW_EXCEPTION_IO_CORRUPT;
  /* Bayer data only: unpack() allocates raw_image for CFA images */
  if (!raw_image || !filters || !raw_width || !raw_height)
    throw LIBRAW_EXCEPTION_UNSUPPORTED_FORMAT;
  /* GPR stores the whole image as one VC-5 stream in a single tile (or
     strip); several tiles are not supported by the GPR SDK either */
  if (tile_width < INT_MAX || tile_length < INT_MAX)
    throw LIBRAW_EXCEPTION_UNSUPPORTED_FORMAT;

  const INT64 memory_limit = INT64(imgdata.rawparams.max_raw_memory_mb) * INT64(1024 * 1024);

  /* Read the compressed stream */
  const INT64 fsize = ifp->size();
  const INT64 offset = data_offset;
  if (offset < 0 || offset >= fsize)
    throw LIBRAW_EXCEPTION_IO_CORRUPT;
  INT64 csize = fsize - offset;
  if (data_size > 0 && INT64(data_size) < csize)
    csize = INT64(data_size);
  if (csize < 8)
    throw LIBRAW_EXCEPTION_IO_CORRUPT;
  if (csize > memory_limit)
    throw LIBRAW_EXCEPTION_TOOBIG;

  vc5_decoder_t d;
  d.csize = size_t(csize);
  /* plain malloc(): the buffers are owned by vc5_decoder_t, not by the
     LibRaw memory manager */
  d.cdata = (uchar *)::malloc(d.csize);
  if (!d.cdata)
    throw LIBRAW_EXCEPTION_ALLOC;
  fseek(ifp, offset, SEEK_SET);
  if (INT64(fread(d.cdata, 1, d.csize, ifp)) != csize)
    throw LIBRAW_EXCEPTION_IO_EOF;

  if (vc5_parse(d))
    throw LIBRAW_EXCEPTION_IO_CORRUPT;
  /* The decoded image replaces the whole raw area */
  if (d.img_w != int(raw_width) || d.img_h != int(raw_height))
    throw LIBRAW_EXCEPTION_IO_CORRUPT;

  d.cw = d.img_w / 2;
  d.ch = d.img_h / 2;
  d.lw[0] = (d.cw + 1) / 2;
  d.lh[0] = (d.ch + 1) / 2;
  for (int level = 1; level < VC5_LEVELS; level++)
  {
    d.lw[level] = (d.lw[level - 1] + 1) / 2;
    d.lh[level] = (d.lh[level - 1] + 1) / 2;
  }
  if (d.lw[VC5_LEVELS - 1] < VC5_MIN_BAND_DIM || d.lh[VC5_LEVELS - 1] < VC5_MIN_BAND_DIM)
    throw LIBRAW_EXCEPTION_IO_CORRUPT;

  /* One block for all bands of all wavelets */
  INT64 samples = 0;
  for (int level = 0; level < VC5_LEVELS; level++)
    samples += INT64(d.lw[level]) * INT64(d.lh[level]) * VC5_BANDS;
  samples *= VC5_CHANNELS;
  const INT64 storage_bytes = samples * INT64(sizeof(short));
  if (storage_bytes + csize > memory_limit)
    throw LIBRAW_EXCEPTION_TOOBIG;
  if (UINT64(storage_bytes) > UINT64(~size_t(0)))
    throw LIBRAW_EXCEPTION_TOOBIG;
  d.storage = (short *)::malloc(size_t(storage_bytes));
  if (!d.storage)
    throw LIBRAW_EXCEPTION_ALLOC;
  {
    short *ptr = d.storage;
    for (int c = 0; c < VC5_CHANNELS; c++)
      for (int level = 0; level < VC5_LEVELS; level++)
        for (int b = 0; b < VC5_BANDS; b++)
        {
          d.plane[c][level][b] = ptr;
          ptr += size_t(d.lw[level]) * size_t(d.lh[level]);
        }
  }

  vc5_build_vlc(d.vlc);

  /* No exception may leave an OpenMP region: the workers return flags */
  checkCancel();
  if (vc5_decode_bands(d))
    throw LIBRAW_EXCEPTION_IO_CORRUPT;
  for (int level = VC5_LEVELS - 1; level > 0; level--)
  {
    checkCancel();
    if (vc5_reconstruct_level(d, level))
      throw LIBRAW_EXCEPTION_ALLOC;
  }
  checkCancel();

  /* The GPR SDK hands 14 bit data to the DNG pipeline for RGGB sensors and
     12 bit data for all others, which are assumed to be GBRG */
  /* (LibRaw may number the second green as color 3) */
  const bool rggb = FC(0, 0) == 0 && (FC(0, 1) & 1) && (FC(1, 0) & 1) && FC(1, 1) == 2;
  const int shift = rggb ? 2 : 4;
  ushort lut[4096];
  for (int i = 0; i < 4096; i++)
    lut[i] = curve[vc5_log_curve[i] >> shift];

  if (vc5_reconstruct_image(d, raw_image, size_t(raw_width), lut, rggb))
    throw LIBRAW_EXCEPTION_ALLOC;

  /* Odd image sizes: the last column/row is not part of the Bayer pattern
     grid and is not written by the reference decoder */
  if (raw_width & 1)
    for (unsigned row = 0; row < raw_height; row++)
      RAW(row, raw_width - 1) = 0;
  if (raw_height & 1)
    for (unsigned col = 0; col < raw_width; col++)
      RAW(raw_height - 1, col) = 0;
}

