/* Walk over the tag-value pairs of the bitstream and collect the position
   and the parameters of all codeblocks. Nothing is decoded here, all offsets
   are validated against the size of the stream.
   Returns non-zero if the stream is damaged or uses unsupported features. */
static int vc5_parse(vc5_decoder_t &d)
{
  const uchar *p = d.cdata;
  const size_t size = d.csize;
  if (size < 8 || memcmp(p, "VC-5", 4))
    return 1;
  size_t pos = 4;

  int channel_count = 0, image_format = 0, pattern_width = 0, pattern_height = 0;
  int channel = 0, subband = 0, quant = 0, precision = 16;
  int prescale[VC5_LEVELS] = {0, 0, 0};
  int level_done[VC5_CHANNELS][VC5_LEVELS];
  bool header_done = false;
  int found = 0;

  memset(level_done, 0, sizeof(level_done));
  memset(d.band, 0, sizeof(d.band));
  d.img_w = d.img_h = 0;

  while (found < VC5_CHANNELS * VC5_SUBBANDS)
  {
    if (size - pos < 4)
      return 1;
    int tag = (int(p[pos]) << 8) | int(p[pos + 1]);
    const int uvalue = (int(p[pos + 2]) << 8) | int(p[pos + 3]);
    const int value = uvalue >= 0x8000 ? uvalue - 0x10000 : uvalue;
    pos += 4;
    if (tag >= 0x8000)
      tag -= 0x10000;
    /* a negative tag marks an optional tag-value pair */
    bool optional = tag < 0;
    if (optional)
      tag = -tag;

    bool header = false, codeblock = false;
    size_t chunk = 0; /* payload size in 32 bit segments */

    switch (tag)
    {
    case VC5_TAG_ChannelCount:
      if (value != VC5_CHANNELS)
        return 1;
      channel_count = value;
      header = true;
      break;
    case VC5_TAG_ImageWidth:
      d.img_w = uvalue;
      header = true;
      break;
    case VC5_TAG_ImageHeight:
      d.img_h = uvalue;
      header = true;
      break;
    case VC5_TAG_ImageFormat:
      if (value != VC5_IMAGE_FORMAT_RAW)
        return 1;
      image_format = value;
      header = true;
      break;
    case VC5_TAG_PatternWidth:
      if (value != 2)
        return 1;
      pattern_width = value;
      header = true;
      break;
    case VC5_TAG_PatternHeight:
      if (value != 2)
        return 1;
      pattern_height = value;
      header = true;
      break;
    case VC5_TAG_ComponentsPerSample:
    case VC5_TAG_MaxBitsPerComponent:
      header = true;
      break;
    case VC5_TAG_SubbandNumber:
      subband = value;
      break;
    case VC5_TAG_Quantization:
      quant = value;
      break;
    case VC5_TAG_LowpassPrecision:
      if (value < 8 || value > 32)
        return 1;
      precision = value;
      break;
    case VC5_TAG_ChannelNumber:
      channel = value;
      break;
    case VC5_TAG_BitsPerComponent:
      break;
    case VC5_TAG_PrescaleShift:
      for (int i = 0; i < VC5_LEVELS; i++)
        prescale[i] = (uvalue >> (14 - i * 2)) & 3;
      break;
    case VC5_TAG_ChannelWidth:
    case VC5_TAG_ChannelHeight:
      /* not allowed in a VC-5 part 3 (image formats) bitstream */
      return 1;
    default:
      if (tag & VC5_TAG_CHUNK_MASK)
      {
        chunk = size_t(uvalue);
        if (tag & VC5_TAG_LARGE_CHUNK)
          chunk += size_t(tag & 0xff) << 16;
      }
      if ((tag & VC5_TAG_LargeCodeblock) == VC5_TAG_LargeCodeblock)
        codeblock = true;
      else
      {
        if (tag == VC5_TAG_UniqueImageIdentifier)
        {
          if (!optional)
            return 1;
        }
        else if (tag == VC5_TAG_InverseTransform || tag == VC5_TAG_InversePermutation)
        {
          /* GoPro uses the fixed Bayer component transform; the payload
             is not interpreted by the reference decoder either */
          if (optional)
            return 1;
        }
        else if (tag == VC5_TAG_InverseTransform16)
          return 1;
        else
        {
          if (tag & VC5_TAG_LARGE_CHUNK)
          {
            /* section header: the elements of the section follow inline */
            optional = true;
            chunk = 0;
          }
          if (!optional) /* unknown tag that must not be ignored */
            return 1;
        }
        if (chunk > (size - pos) / 4)
          return 1;
        pos += chunk * 4;
      }
      break;
    }

    if (header)
    {
      /* header parameters are not allowed after the header */
      if (header_done)
        return 1;
    }
    else
      header_done = true;

    if (!codeblock)
      continue;

    if (channel_count != VC5_CHANNELS || image_format != VC5_IMAGE_FORMAT_RAW ||
        pattern_width != 2 || pattern_height != 2 || !d.img_w || !d.img_h)
      return 1;
    if (channel < 0 || channel >= VC5_CHANNELS || subband < 0 || subband >= VC5_SUBBANDS)
      return 1;
    vc5_band_t &b = d.band[channel][subband];
    if (b.present)
      return 1;
    if (chunk > (size - pos) / 4)
      return 1;
    b.offset = pos;
    b.bytes = chunk * 4;
    b.quant = quant;
    b.precision = precision;
    b.present = 1;
    pos += chunk * 4;
    found++;

    /* The reference decoder inverts a wavelet as soon as all of its bands
       are there, using the prescale shift that is in effect at this time */
    for (int level = VC5_LEVELS - 1; level > 0; level--)
    {
      if (level_done[channel][level])
        continue;
      bool complete = (level == VC5_LEVELS - 1) || level_done[channel][level + 1];
      for (int sb = 0; sb < VC5_SUBBANDS && complete; sb++)
        if (vc5_subband_level[sb] == level && !d.band[channel][sb].present)
          complete = false;
      if (!complete)
        break;
      level_done[channel][level] = 1;
      d.prescale[channel][level] = prescale[level];
    }

    if (++subband == VC5_SUBBANDS)
    {
      channel++;
      subband = 0;
    }
  }
  /* the last inverse transform is done after the whole stream was read */
  for (int c = 0; c < VC5_CHANNELS; c++)
    d.prescale[c][0] = prescale[0];
  return 0;
}

/* ------------------------------------------------------------------------
   Inverse wavelet transform (2/6 wavelet). All intermediate values are
   computed in 32 bit; inputs are 16 bit, so nothing can overflow.
   ------------------------------------------------------------------------ */

/* Vertical step for one column range. 'border' is 0 for the first row,
   1 for inner rows and 2 for the last row; a0..a2 are
     first row: rows 0, 1, 2
     inner row: rows r-1, r, r+1
     last row:  rows r, r-1, r-2                                        */
static void vc5_inverse_vertical(const short *a0, const short *a1, const short *a2,
                                 const short *high, int n, int border,
                                 short *even, short *odd)
{
  int i;
  if (border == 0)
  {
    for (i = 0; i < n; i++)
    {
      const int e = ((11 * a0[i] - 4 * a1[i] + a2[i] + 4) >> 3) + high[i];
      const int o = ((5 * a0[i] + 4 * a1[i] - a2[i] + 4) >> 3) - high[i];
      even[i] = short(vc5_clamp16(e >> 1));
      odd[i] = short(vc5_clamp16(o >> 1));
    }
  }
  else if (border == 1)
  {
    for (i = 0; i < n; i++)
    {
      const int e = ((a0[i] - a2[i] + 4) >> 3) + a1[i] + high[i];
      const int o = ((a2[i] - a0[i] + 4) >> 3) + a1[i] - high[i];
      even[i] = short(vc5_clamp16(e >> 1));
      odd[i] = short(vc5_clamp16(o >> 1));
    }
  }
  else
  {
    for (i = 0; i < n; i++)
    {
      const int e = ((5 * a0[i] + 4 * a1[i] - a2[i] + 4) >> 3) + high[i];
      const int o = ((11 * a0[i] - 4 * a1[i] + a2[i] + 4) >> 3) - high[i];
      even[i] = short(vc5_clamp16(e >> 1));
      odd[i] = short(vc5_clamp16(o >> 1));
    }
  }
}

/* Final scaling of the horizontal step. Without prescale the result is
   halved and limited to 14 bits; with prescale the encoder's shift is undone
   (the halving is skipped for a prescale shift of 2) */
struct vc5_scale_plain
{
  static inline short f(int v, int) { return short(vc5_clamp_u14(v >> 1)); }
};
struct vc5_scale_descale
{
  static inline short f(int v, int mul) { return short(vc5_clamp16(v * mul)); }
};

/* Horizontal step: in_w lowpass/highpass values give out_w output values,
   out_w is 2*in_w or 2*in_w-1; in_w >= 3 */
template <class SCALE>
static void vc5_inverse_horizontal(const short *low, const short *high, int in_w,
                                   short *out, int out_w, int mul)
{
  const int last = in_w - 1;
  int e, o, i;

  e = ((11 * low[0] - 4 * low[1] + low[2] + 4) >> 3) + high[0];
  o = ((5 * low[0] + 4 * low[1] - low[2] + 4) >> 3) - high[0];
  out[0] = SCALE::f(e, mul);
  out[1] = SCALE::f(o, mul);

  for (i = 1; i < last; i++)
  {
    e = ((low[i - 1] - low[i + 1] + 4) >> 3) + low[i] + high[i];
    o = ((low[i + 1] - low[i - 1] + 4) >> 3) + low[i] - high[i];
    out[2 * i] = SCALE::f(e, mul);
    out[2 * i + 1] = SCALE::f(o, mul);
  }

  e = ((5 * low[last] + 4 * low[last - 1] - low[last - 2] + 4) >> 3) + high[last];
  out[2 * last] = SCALE::f(e, mul);
  if (2 * last + 1 < out_w)
  {
    o = ((11 * low[last] - 4 * low[last - 1] + low[last - 2] + 4) >> 3) - high[last];
    out[2 * last + 1] = SCALE::f(o, mul);
  }
}

/* Invert input row 'r' of one wavelet: writes output row 2*r to out_even
   and, if out_odd is not null, row 2*r+1 to out_odd.
   tmp: scratch space for 4*lw[level] values */
static void vc5_inverse_row(const vc5_decoder_t &d, int channel, int level, int r,
                            short *tmp, short *out_even, short *out_odd, int out_w)
{
  const int in_w = d.lw[level], in_h = d.lh[level];
  const size_t pitch = size_t(in_w);
  const short *ll = d.plane[channel][level][0];
  const short *lh = d.plane[channel][level][1];
  const short *hl = d.plane[channel][level][2] + pitch * r;
  const short *hh = d.plane[channel][level][3] + pitch * r;
  short *even_low = tmp, *odd_low = tmp + pitch;
  short *even_high = tmp + 2 * pitch, *odd_high = tmp + 3 * pitch;

  if (r == 0)
  {
    vc5_inverse_vertical(ll, ll + pitch, ll + 2 * pitch, hl, in_w, 0, even_low, odd_low);
    vc5_inverse_vertical(lh, lh + pitch, lh + 2 * pitch, hh, in_w, 0, even_high, odd_high);
  }
  else if (r < in_h - 1)
  {
    const short *a = ll + pitch * (r - 1), *b = lh + pitch * (r - 1);
    vc5_inverse_vertical(a, a + pitch, a + 2 * pitch, hl, in_w, 1, even_low, odd_low);
    vc5_inverse_vertical(b, b + pitch, b + 2 * pitch, hh, in_w, 1, even_high, odd_high);
  }
  else
  {
    const short *a = ll + pitch * r, *b = lh + pitch * r;
    vc5_inverse_vertical(a, a - pitch, a - 2 * pitch, hl, in_w, 2, even_low, odd_low);
    vc5_inverse_vertical(b, b - pitch, b - 2 * pitch, hh, in_w, 2, even_high, odd_high);
  }

  const int prescale = d.prescale[channel][level];
  if (prescale > 1)
  {
    const int mul = (prescale == 2) ? 2 : 1;
    vc5_inverse_horizontal<vc5_scale_descale>(even_low, even_high, in_w, out_even, out_w, mul);
    if (out_odd)
      vc5_inverse_horizontal<vc5_scale_descale>(odd_low, odd_high, in_w, out_odd, out_w, mul);
  }
  else
  {
    vc5_inverse_horizontal<vc5_scale_plain>(even_low, even_high, in_w, out_even, out_w, 0);
    if (out_odd)
      vc5_inverse_horizontal<vc5_scale_plain>(odd_low, odd_high, in_w, out_odd, out_w, 0);
  }
}

/* Entropy decoding of all bands. The codeblocks are independent. */
static int vc5_decode_bands(vc5_decoder_t &d)
{
  int err = 0;
  int i;
#ifdef LIBRAW_USE_OPENMP
#pragma omp parallel for default(shared) private(i) schedule(dynamic, 1)
#endif
  for (i = 0; i < VC5_CHANNELS * VC5_SUBBANDS; i++)
  {
    /* largest bands first */
    const int subband = VC5_SUBBANDS - 1 - i / VC5_CHANNELS;
    const int channel = i % VC5_CHANNELS;
    const int level = vc5_subband_level[subband];
    const vc5_band_t &b = d.band[channel][subband];
    short *out = d.plane[channel][level][vc5_subband_band[subband]];
    const size_t total = size_t(d.lw[level]) * size_t(d.lh[level]);
    int rc;
    if (subband == 0)
      rc = vc5_decode_lowpass(d.cdata + b.offset, b.bytes, out, total, b.precision);
    else
      rc = vc5_decode_highpass(d.cdata + b.offset, b.bytes, out, total, b.quant, d.vlc);
    if (rc)
    {
#ifdef LIBRAW_USE_OPENMP
#pragma omp atomic
#endif
      err |= 1;
    }
  }
  return err;
}

/* Reconstruct the lowpass band of wavelet level-1 from the bands of the
   wavelet 'level' (level > 0) in all channels */
static int vc5_reconstruct_level(vc5_decoder_t &d, int level)
{
  const int in_w = d.lw[level], in_h = d.lh[level];
  const int out_w = d.lw[level - 1], out_h = d.lh[level - 1];
  const int total = VC5_CHANNELS * in_h;
  int err = 0;
#ifdef LIBRAW_USE_OPENMP
#pragma omp parallel default(shared)
#endif
  {
    int i;
    short *tmp = (short *)malloc(sizeof(short) * 4 * size_t(in_w));
    if (!tmp)
    {
#ifdef LIBRAW_USE_OPENMP
#pragma omp atomic
#endif
      err |= 1;
    }
#ifdef LIBRAW_USE_OPENMP
#pragma omp for schedule(static)
#endif
    for (i = 0; i < total; i++)
    {
      if (!tmp)
        continue;
      const int channel = i / in_h, r = i % in_h;
      short *even = d.plane[channel][level - 1][0] + size_t(out_w) * size_t(2 * r);
      short *odd = (2 * r + 1 < out_h) ? even + out_w : 0;
      vc5_inverse_row(d, channel, level, r, tmp, even, odd, out_w);
    }
    if (tmp)
      free(tmp);
  }
  return err;
}

/* Last inverse transform, inverse component transform and output curve:
   writes 2*ch rows of 2*cw pixels to the Bayer image.
   lut: 12 bit -> output value; rggb: RGGB layout, otherwise GBRG */
static int vc5_reconstruct_image(vc5_decoder_t &d, ushort *raw, size_t stride,
                                 const ushort *lut, bool rggb)
{
  const int in_w = d.lw[0], in_h = d.lh[0];
  const int cw = d.cw, ch = d.ch;
  int err = 0;
#ifdef LIBRAW_USE_OPENMP
#pragma omp parallel default(shared)
#endif
  {
    int r;
    short *tmp = (short *)malloc(sizeof(short) * (4 * size_t(in_w) + 2 * VC5_CHANNELS * size_t(cw)));
    if (!tmp)
    {
#ifdef LIBRAW_USE_OPENMP
#pragma omp atomic
#endif
      err |= 1;
    }
#ifdef LIBRAW_USE_OPENMP
#pragma omp for schedule(static)
#endif
    for (r = 0; r < in_h; r++)
    {
      if (!tmp)
        continue;
      short *comp = tmp + 4 * size_t(in_w); /* [channel][even/odd][cw] */
      const int rows = (2 * r + 1 < ch) ? 2 : 1;
      for (int c = 0; c < VC5_CHANNELS; c++)
      {
        short *even = comp + size_t(2 * c) * cw;
        vc5_inverse_row(d, c, 0, r, tmp, even, rows == 2 ? even + cw : 0, cw);
      }
      for (int k = 0; k < rows; k++)
      {
        const short *gs = comp + size_t(0 + k) * cw;
        const short *rg = comp + size_t(2 + k) * cw;
        const short *bg = comp + size_t(4 + k) * cw;
        const short *gd = comp + size_t(6 + k) * cw;
        ushort *row1 = raw + stride * (size_t(2 * r + k) * 2);
        ushort *row2 = row1 + stride;
        for (int col = 0; col < cw; col++)
        {
          /* component values are unsigned 16 bit in the reference */
          const int GS = ushort(gs[col]);
          const int RG = int(ushort(rg[col])) - 2048;
          const int BG = int(ushort(bg[col])) - 2048;
          const int GD = int(ushort(gd[col])) - 2048;
          int R = RG * 2 + GS;
          int B = BG * 2 + GS;
          int G1 = GS + GD;
          int G2 = GS - GD;
          R = R < 0 ? 0 : (R > 4095 ? 4095 : R);
          B = B < 0 ? 0 : (B > 4095 ? 4095 : B);
          G1 = G1 < 0 ? 0 : (G1 > 4095 ? 4095 : G1);
          G2 = G2 < 0 ? 0 : (G2 > 4095 ? 4095 : G2);
          if (rggb)
          {
            row1[2 * col] = lut[R];
            row1[2 * col + 1] = lut[G1];
            row2[2 * col] = lut[G2];
            row2[2 * col + 1] = lut[B];
          }
          else
          {
            row1[2 * col] = lut[G1];
            row1[2 * col + 1] = lut[B];
            row2[2 * col] = lut[R];
            row2[2 * col + 1] = lut[G2];
          }
        }
      }
    }
    if (tmp)
      free(tmp);
  }
  return err;
}

